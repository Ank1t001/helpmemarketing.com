#!/usr/bin/env python3
"""Make site_shell.html from the live Med Spa Index page (run once, or again when the shared Index head changes).

    python3 tools/make_shell.py

Keeps the Med Spa page's theme script, icons, fonts, stylesheet, consent default, GTM loader, shared scripts, the .msi
styles, nav, footer and wrapper. Replaces its page metadata with {{META}}, its JSON-LD with {{JSONLD}}, its report body with
{{BODY}} between DENTAL INDEX REPORT BODY markers, and adds {{HEAD_EXTRA}} before </head>. Writes the source page's commit
into the shell so the copy is traceable.
"""
import re, subprocess
from pathlib import Path
HERE = Path(__file__).resolve().parent.parent
REPO = HERE.parent.parent
src = (REPO / "medspa-index.html").read_text(encoding="utf-8")
commit = subprocess.run(["git", "log", "-1", "--format=%h", "--", "medspa-index.html"], cwd=REPO, capture_output=True, text=True).stdout.strip()

def one(pattern, repl, s, flags=re.S):
    s2, n = re.subn(pattern, repl, s, count=1, flags=flags)
    if n != 1: raise SystemExit(f"make_shell: expected one match for {pattern[:60]}")
    return s2

s = one(r"<title>.*?(?=<!-- Consent default)", "{{META}}\n", src)
blocks = re.findall(r'<script type="application/ld\+json">.*?</script>\n?', s, re.S)
if not blocks: raise SystemExit("make_shell: no JSON-LD found")
s = s.replace(blocks[0], "{{JSONLD}}\n", 1)
for b in blocks[1:]: s = s.replace(b, "", 1)
s = one(r"<!-- ===== GTA MEDSPA INDEX REPORT BODY START =====.*?<!-- ===== GTA MEDSPA INDEX REPORT BODY END ===== -->",
        "<!-- ===== DENTAL INDEX REPORT BODY START ===== generated by _kit/dental-implants/build.py; edit the kit, never this block ===== -->\n{{BODY}}\n<!-- ===== DENTAL INDEX REPORT BODY END ===== -->", s)
s = one(r'data-screen-label="gta-medspa-index"', 'data-screen-label="dental-index"', s)
s = one(r"</head>", f"<!-- Shell copied from medspa-index.html at commit {commit} by _kit/dental-implants/tools/make_shell.py -->\n{{{{HEAD_EXTRA}}}}\n</head>", s)
(HERE / "site_shell.html").write_text(s, encoding="utf-8")
print("site_shell.html from medspa-index.html", commit, len(s))
