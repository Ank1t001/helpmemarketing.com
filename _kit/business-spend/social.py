"""Instagram content module for the Business Cards & Spend Management Index.

Two files make the module:

- social.json: the derived records, written only by social_derive.py from the private evidence package
  (accounts, posts with derived fields, corrections to the collector's handoff, excluded material as counts).
- social_narrative.json: the editorial layer (the view's wording, scope note, patterns and selected examples).

Gating (owner's instruction of 27 October 2026): status "review" shows the "Instagram content" view on the
staging draft for editorial review only; the release build is blocked (validate.check_inputs) until status is
"reviewed" and the owner's approval is recorded in social.json by hand. Status "draft" (a fresh ingest) shows
nothing. Approval is never generated by a script.

Fixed rules (SOCIAL_MODULE_BRIEF.md): official company Instagram accounts only (LinkedIn dropped by the owner,
26 October 2026); posts published 25 July through 22 October 2026 inclusive, America/Toronto (90 complete days);
the window never moves. Website observation dates are separate and unchanged.
"""
