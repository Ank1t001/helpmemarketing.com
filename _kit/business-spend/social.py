METRICS = {'instagram': ('likes', 'comments', 'views')}
METRIC_META = ('captured_at', 'likes_comments_captured_at', 'views_captured_at', 'views_time_precision', 'views_source')
ACCOUNT_FIELDS = ('platform', 'channel', 'handle', 'url', 'verified', 'verification', 'scope', 'logged_in', 'checked_at', 'coverage',
                  'coverage_note', 'earliest_reached', 'posts_in_window')
VIDEO_LABEL = 'Cover and caption reviewed; video not watched.'
UNRESOLVED_LABEL = 'records with unresolved provider attribution'
# Claims about a whole reel that only its caption and cover support (the video was not watched).
WHOLE_POST = re.compile(r"\b(?:the|this) (?:post|reel|video) (?:names no|does not (?:say|state|name|mention)|doesn't|omits|leaves out|says nothing)|\bfrom the (?:post|reel)\b", re.I)
BANNED = re.compile(r'(best[- ]performing|top[- ]performing|\bviral\b|went viral|engagement rate|outperform|paid promotion|\bboosted post|\bboosting\b|lead generation|\brevenue\b|\bconversions?\b|\binactive\b|\bdormant\b|\bstrategy\b|\btargeting\b|\bad spend\b)', re.I)

# Credential patterns only (owner's instruction, 27 October 2026). Ordinary words such as "session", "cookie" or
# "token" are not credentials and are not rejected; values that look like real cookies, tokens or keys are.
SECRET_PATTERNS = [
    ('cookie header', r'(?im)^\s*(?:set-)?cookie\s*:\s*\S'),
    ('Instagram or web session cookie', r'(?i)\b(?:sessionid|csrftoken|ds_user_id|ig_did|shbid|shbts|rur|datr|_vercel_jwt|__Secure-[\w-]+|__Host-[\w-]+)\s*[=:]\s*["\']?[\w%.:-]{6,}'),
    ('authorization header', r'(?i)\bauthorization\s*:\s*\S{8,}'),
    ('bearer token', r'(?i)\bbearer\s+[A-Za-z0-9\-._~+/]{20,}=*'),
    ('JSON web token', r'\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}'),
    ('password or key assignment', r'(?i)\b(?:password|passwd|api[_-]?key|access[_-]?token|refresh[_-]?token|client[_-]?secret|secret[_-]?key)\s*["\']?\s*[=:]\s*["\']?[^\s"\']{6,}'),
    ('private storage reference', r'\blibfile_[0-9a-f]{16,}'),
    ('private cloud-storage link', r'(?i)drive\.google\.com/(?:file/d|open\?id=|uc\?)|drive\.usercontent\.google\.com|docs\.google\.com/\S+/d/[\w-]{20,}'),
    ('share token', r'(?i)[?&]_vercel_share=[\w-]{8,}'),
    ('cloud key', r'\b(?:AKIA[0-9A-Z]{16}|AIza[0-9A-Za-z_-]{35}|ghp_[0-9A-Za-z]{36}|xox[bpsa]-[0-9A-Za-z-]{10,})'),
]


def secret_findings(text):
    """Return the names of credential patterns found in text (empty list when clean)."""
    return [name for name, rx in SECRET_PATTERNS if re.search(rx, text)]


def inspection_label(fmt, inspection):
    if fmt == 'video' and inspection == 'partial':
        return VIDEO_LABEL
    if fmt == 'video' and inspection == 'watched_in_full':
        return 'Watched in full.'
    if fmt == 'carousel' and inspection == 'all_slides':
        return 'Every slide reviewed, with the caption.'
    if fmt == 'carousel' and inspection == 'partial':
        return 'Some slides reviewed; only the retained slides are analysed.'
    if inspection == 'cover_and_caption':
        return 'Image and caption reviewed.'
    return 'Partly reviewed.'


def long_day(iso):
    d = date.fromisoformat(iso[:10])
    return '%d %s %d' % (d.day, ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'][d.month - 1], d.year)


def clock(ts):
    d = datetime.fromisoformat(ts)
    return '%d:%02d %s' % ((d.hour - 1) % 12 + 1, d.minute, 'a.m.' if d.hour < 12 else 'p.m.')


def window_text(s=None):
    a = date.fromisoformat(WINDOW['start'])
    b = date.fromisoformat(WINDOW['end'])
    m = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
    return '%d %s to %d %s %d, Toronto time (%d days)' % (a.day, m[a.month - 1], b.day, m[b.month - 1], b.year, WINDOW['days'])


def _in_window(d):
    return WINDOW['start'] <= d <= WINDOW['end']


def check(s, asset_root=None):
    """Return a list of errors for social.json (or a package converted by package_to_module)."""
    errs = []
    if s.get('window') != WINDOW:
        errs.append('social: window must be exactly %s (it never moves)' % json.dumps(WINDOW))
    if (date.fromisoformat(WINDOW['end']) - date.fromisoformat(WINDOW['start'])).days + 1 != WINDOW['days']:
        errs.append('social: window length is not %d days' % WINDOW['days'])
    if s.get('status') not in ('draft', 'review', 'reviewed'):
        errs.append('social: status must be draft, review or reviewed')
    if s.get('status') == 'reviewed' and not (s.get('approved') or '').strip():
        errs.append('social: reviewed without the owner approval recorded by hand')
    if s.get('status') in ('draft', 'review') and s.get('approved'):
        errs.append('social: an approval is recorded but the status is %s' % s.get('status'))
    found = secret_findings(json.dumps(s, ensure_ascii=False))
    if found:
        errs.append('social: credential-like material found (%s); remove it before anything is stored here' % ', '.join(found))
    accts = {}
    for a in s.get('accounts', []):
        for k in ACCOUNT_FIELDS:
            if k not in a:
                errs.append('social account %s/%s: missing %s' % (a.get('platform'), a.get('channel'), k))
        if a.get('platform') not in PLATFORMS:
            errs.append('social account: unknown platform %r' % a.get('platform'))
        if a.get('channel') not in CHANNELS:
            errs.append('social account %s: channel %r is out of scope (Instagram only)' % (a.get('platform'), a.get('channel')))
        if a.get('scope') not in SCOPES:
            errs.append('social account %s/%s: scope must be one of %s' % (a.get('platform'), a.get('channel'), SCOPES))
        if a.get('coverage') not in COVERAGE:
            errs.append('social account %s/%s: coverage must be one of %s' % (a.get('platform'), a.get('channel'), tuple(COVERAGE)))
        if a.get('coverage') == 'complete' and a.get('posts_in_window') is None:
            errs.append('social account %s/%s: a complete inventory needs its post count' % (a.get('platform'), a.get('channel')))
        if a.get('coverage') in ('blocked', 'no_account', 'unverified') and a.get('posts_in_window') is not None:
            errs.append('social account %s/%s: no post count for %s coverage' % (a.get('platform'), a.get('channel'), a.get('coverage')))
        if a.get('coverage') == 'complete' and (a.get('earliest_reached') or '9999') >= WINDOW['start']:
            errs.append('social account %s/%s: complete only if the feed was read past the window start' % (a.get('platform'), a.get('channel')))
        if a.get('verified') is not True and a.get('coverage') in ('complete', 'partial'):
            errs.append('social account %s/%s: posts from an unverified account cannot be used' % (a.get('platform'), a.get('channel')))
        if 'attribution' in a and a['attribution'].get('status') not in ATTRIBUTION:
            errs.append('social account %s: attribution status must be one of %s' % (a.get('platform'), ATTRIBUTION))
        if a.get('posts_in_window') == 0 and 'attribution' in a and not a.get('no_posts_text', '').startswith('No in-window posts found in the reviewed'):
            errs.append('social account %s: no posts is written "No in-window posts found in the reviewed ..." (never inactive)' % a.get('platform'))
        try:
            datetime.fromisoformat(a.get('checked_at') or '')
        except ValueError:
            errs.append('social account %s/%s: record when the account was checked (checked_at, ISO time with offset)' % (a.get('platform'), a.get('channel')))
        if not isinstance(a.get('logged_in'), bool):
            errs.append('social account %s/%s: record whether the browser was logged in (true or false)' % (a.get('platform'), a.get('channel')))
        accts[(a.get('platform'), a.get('channel'))] = a
    ids, urls = set(), set()
    for p in s.get('posts', []):
        pid = p.get('id', '?')
        for k in POST_FIELDS:
            if k not in p:
                errs.append('social post %s: missing %s (record a missing value as null, never leave it out)' % (pid, k))
        if pid in ids:
            errs.append('social post %s: duplicate id' % pid)
        if p.get('url') in urls:
            errs.append('social post %s: duplicate URL (grid and Reels counted twice)' % pid)
        ids.add(pid)
        urls.add(p.get('url'))
        a = accts.get((p.get('platform'), p.get('channel')))
        if not a or not a.get('verified'):
            errs.append('social post %s: not from a verified official account in the accounts list' % pid)
        elif a.get('handle') != p.get('account'):
            errs.append('social post %s: account %r does not match the verified handle' % (pid, p.get('account')))
        d = p.get('published_on') or ''
        if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', d) or not _in_window(d):
            errs.append('social post %s: published_on %r is outside %s to %s' % (pid, d, WINDOW['start'], WINDOW['end']))
        if p.get('date_method') not in DATE_METHODS:
            errs.append('social post %s: date_method must be one of %s' % (pid, DATE_METHODS))
        try:
            datetime.fromisoformat(p.get('captured_at') or '')
        except ValueError:
            errs.append('social post %s: captured_at must be an ISO time with offset' % pid)
        if p.get('relation') not in RELATIONS:
            errs.append('social post %s: relation must be one of %s' % (pid, RELATIONS))
        if p.get('relation') == 'repost':
            errs.append('social post %s: reposts cannot be dated to the window and are not counted' % pid)
        if 'publisher' in p:
            if p['relation'] == 'original' and p['publisher'] != p['account']:
                errs.append('social post %s: an original is published by the account itself' % pid)
            if p['relation'] == 'collaboration' and p.get('collaboration') not in ('published_by_collaborator', 'published_with_coauthor'):
                errs.append('social post %s: a collaboration records who published it' % pid)
            if p.get('collaboration') == 'published_by_collaborator' and p['publisher'] == p['account']:
                errs.append('social post %s: published by a collaborator, but the publisher is the account' % pid)
            if '/%s/' % p['publisher'] not in p['url']:
                errs.append('social post %s: publisher does not match the post URL' % pid)
        if p.get('format') not in FORMATS:
            errs.append('social post %s: format must be one of %s' % (pid, FORMATS))
        if p.get('inspection') not in INSPECTION:
            errs.append('social post %s: inspection must be one of %s' % (pid, INSPECTION))
        if p.get('format') == 'video' and p.get('inspection') not in ('watched_in_full', 'partial'):
            errs.append('social post %s: a video is analysed only after it is watched (or labelled partial)' % pid)
        if p.get('format') == 'carousel' and p.get('inspection') not in ('all_slides', 'partial'):
            errs.append('social post %s: a carousel is analysed only after every slide is inspected (or labelled partial)' % pid)
        if 'inspection_label' in p and p['inspection_label'] != inspection_label(p.get('format'), p.get('inspection')):
            errs.append('social post %s: inspection label does not match the inspection' % pid)
        if p.get('scope') not in SCOPES:
            errs.append('social post %s: scope must be one of %s' % (pid, SCOPES))
        mt = p.get('metrics') or {}
        want = METRICS.get(p.get('channel'), ())
        for k in want:
            if k not in mt:
                errs.append('social post %s: metric %s missing; record null when it is not shown' % (pid, k))
            elif mt[k] is not None and not isinstance(mt[k], int) and not re.fullmatch(r'\d+(?:\.\d+)?[KM]', str(mt[k])):
                errs.append('social post %s: metric %s must be a whole number or the displayed abbreviation (e.g. 11.1K)' % (pid, k))
        if 'likes_comments_captured_at' in mt:
            if (mt.get('likes') is not None or mt.get('comments') is not None) and not mt.get('likes_comments_captured_at'):
                errs.append('social post %s: likes and comments need their own capture time' % pid)
            if mt.get('views') is not None and not (mt.get('views_captured_at') and mt.get('views_source')):
                errs.append('social post %s: views need their own read time and source' % pid)
        elif any(mt.get(k) is not None for k in want) and not mt.get('captured_at'):
            errs.append('social post %s: metrics need their own capture time' % pid)
        for k in mt:
            if k not in want and k not in METRIC_META:
                errs.append('social post %s: metric %s is not recorded for %s' % (pid, k, p.get('channel')))
    partial = any(a.get('coverage') in ('partial', 'blocked', 'unverified') for a in s.get('accounts', []))
    for row in s.get('summary', []):
        if partial and any(k in row for k in ('frequency', 'share', 'proportion', 'posts_per_week')):
            errs.append('social summary: frequency or topic proportions need a complete inventory for every account in the row')
    for a in s.get('accounts', []):
        n = sum(1 for p in s.get('posts', []) if p.get('platform') == a.get('platform') and p.get('channel') == a.get('channel'))
        if a.get('coverage') == 'complete' and s.get('posts') is not None and a.get('posts_in_window') != n:
            errs.append('social account %s: posts_in_window %s but %d posts recorded' % (a.get('platform'), a.get('posts_in_window'), n))
    return errs


def load_narrative(path=None):
    with open(path or NARRATIVE, encoding='utf-8') as f:
        return json.load(f)


def _segments_text(segs):
    return ''.join(x if isinstance(x, str) else x.get('q', x.get('t', '')) for x in segs)


def _editorial_text(segs):
    return ''.join(x if isinstance(x, str) else x.get('t', '') for x in segs)


def check_narrative(s, n, asset_root=None):
    """Errors in the editorial layer, checked against the derived records."""
    errs = []
    posts = {p['id']: p for p in s.get('posts', [])}
    accts = {a['platform']: a for a in s.get('accounts', [])}
    if n.get('view', {}).get('title') != 'Social Media Content':
        errs.append('social narrative: the view is titled "Social Media Content" (renamed 2026-10-30)')
    if 'This edition reviews Instagram content only.' not in n.get('view', {}).get('dek', ''):
        errs.append('social narrative: the view must say that this edition reviews Instagram content only')
    per = {}
    for ex in n.get('examples', []):
        p = posts.get(ex.get('post'))
        if not p:
            errs.append('social example %s: unknown post %r' % (ex.get('id'), ex.get('post')))
            continue
        per[p['platform']] = per.get(p['platform'], 0) + 1
        for k in ('id', 'title', 'approach', 'shows', 'reading', 'take'):
            if not ex.get(k):
                errs.append('social example %s: missing %s' % (ex.get('id'), k))
        if accts.get(p['platform'], {}).get('attribution', {}).get('status') == 'unresolved':
            errs.append('social example %s: %s attribution is unresolved; no example or conclusion rests on it' % (ex.get('id'), p['platform']))
        if p['format'] == 'carousel' and p['inspection'] == 'partial':
            errs.append('social example %s: a partly inspected carousel is not used as an example' % ex.get('id'))
        quotes = [x['q'] for x in ex['shows'] if isinstance(x, dict) and 'q' in x]
        if not quotes:
            errs.append('social example %s: quote the post (short exact phrases)' % ex.get('id'))
        for q in quotes:
            if len(q) > 140:
                errs.append('social example %s: quotes stay short (under 140 characters)' % ex.get('id'))
        take = ex.get('take', '')
        sentences = [x for x in re.split(r'(?<=[.?!])\s+', take.strip()) if x]
        if not 2 <= len(sentences) <= 3:
            errs.append('social example %s: the takeaway is two or three sentences (%d)' % (ex.get('id'), len(sentences)))
        if '?' not in take and 'Measure' not in take:
            errs.append('social example %s: the takeaway carries one question or one test with a measure' % ex.get('id'))
        if re.search(r'\b(?:will|would) (?:raise|lift|increase|reduce|improve)', take) and 'Hypothesis' not in take:
            errs.append('social example %s: a predicted effect is labelled as a hypothesis' % ex.get('id'))
        for field in ('reading', 'take', 'title', 'approach'):
            m = BANNED.search(ex.get(field, ''))
            if m:
                errs.append('social example %s: %r is not a claim this module can make' % (ex.get('id'), m.group(0)))
        m = BANNED.search(_editorial_text(ex['shows']) + _editorial_text(ex.get('website', [])))
        if m:
            errs.append('social example %s: %r is not a claim this module can make' % (ex.get('id'), m.group(0)))
        if p['format'] == 'video' and p['inspection'] != 'watched_in_full':
            ed = ' '.join([ex.get('reading', ''), ex.get('take', ''), _editorial_text(ex['shows']), _editorial_text(ex.get('website', []))])
            m = WHOLE_POST.search(ed)
            if m:
                errs.append('social example %s: the video was not watched, so %r overstates what the post omits (limit it to the caption and cover)' % (ex.get('id'), m.group(0)))
        img = ex.get('image')
        if img:
            for k in ('src', 'width', 'height', 'alt', 'credit', 'from', 'from_sha256', 'crop', 'sanitisation', 'sha256'):
                if not img.get(k):
                    errs.append('social example %s: image needs %s' % (ex.get('id'), k))
            if not img.get('src', '').startswith(IMG_DIR):
                errs.append('social example %s: images live under %s' % (ex.get('id'), IMG_DIR))
            elif asset_root:
                f = os.path.join(asset_root, img['src'].lstrip('/'))
                if not os.path.exists(f):
                    errs.append('social example %s: image file missing' % ex.get('id'))
                else:
                    with open(f, 'rb') as fh:
                        if hashlib.sha256(fh.read()).hexdigest() != img.get('sha256'):
                            errs.append('social example %s: image file does not match its recorded hash' % ex.get('id'))
            if img.get('from') != p['capture_ref'] and not img.get('from', '').startswith(p['capture_ref'][:-4]):
                errs.append('social example %s: image is not derived from the post\'s own capture' % ex.get('id'))
            if img.get('from_sha256') and p.get('capture_sha256') and img.get('from') == p['capture_ref'] and img['from_sha256'] != p['capture_sha256']:
                errs.append('social example %s: image source hash differs from the capture' % ex.get('id'))
        elif not ex.get('no_image_reason'):
            errs.append('social example %s: give the image or say why a text excerpt is used instead' % ex.get('id'))
    for pl, k in per.items():
        if k > 2:
            errs.append('social examples: %s has %d (at most two, the second only for a distinct lesson)' % (pl, k))
    for pt in n.get('patterns', []):
        for k in ('title', 'body', 'denominator'):
            if not pt.get(k):
                errs.append('social pattern %r: missing %s' % (pt.get('title'), k))
        m = BANNED.search(pt.get('title', '') + ' ' + pt.get('body', ''))
        if m:
            errs.append('social pattern %r: %r is not a claim this module can make' % (pt.get('title'), m.group(0)))
    blob = json.dumps(n, ensure_ascii=False)
    if '—' in blob:
        errs.append('social narrative: em dash')
    if secret_findings(blob):
        errs.append('social narrative: credential-like material')
    return errs


def _load(path=None, npath=None):
    if not os.path.exists(path or PATH):
        return None
    with open(path or PATH, encoding='utf-8') as f:
        s = json.load(f)
    if s.get('status') not in ('review', 'reviewed'):
        return None
    n = load_narrative(npath)
    errs = check(s, ROOT) + check_narrative(s, n, ROOT)
    if errs:
        raise SystemExit('social.json is marked %s but fails its checks:\n  ' % s.get('status') + '\n  '.join(errs))
    s = dict(s)
    s['narrative'] = n
    s['view'] = n['view']
    return s


def load_module(path=None, npath=None):
    """The module for the page: status review (staging review) or reviewed. A draft or missing file gives None."""
    return _load(path, npath)


def load_reviewed(path=None, npath=None):
    """Only a module the owner has approved by hand (status reviewed, approval recorded)."""
    s = _load(path, npath)
    if s and s.get('status') == 'reviewed' and (s.get('approved') or '').strip():
        return s
    return None


def release_gate(s):
    if s and s.get('status') != 'reviewed':
        return ['social: the Instagram content view is shown for editorial review only (social.json status %r); the owner records approval by hand before release' % s.get('status')]
    return []


