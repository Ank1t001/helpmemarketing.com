def _rich(segs):
    out = []
    for x in segs:
        if isinstance(x, str):
            out.append(E(x))
        elif 'q' in x:
            out.append('&ldquo;%s&rdquo;' % E(x['q']))
        elif 'a' in x:
            out.append('<a href="%s">%s</a>' % (E(x['a']), E(x['t'])))
    return ''.join(out)


def _collab_text(p):
    if p['relation'] == 'original':
        return '@%s (not a collaboration)' % p['publisher']
    if p['collaboration'] == 'published_by_collaborator':
        t = '@%s, with @%s as collaborator' % (p['publisher'], p['account'])
    else:
        t = '@%s, with co-authors (%s)' % (p['publisher'], p['header'])
    if p.get('paid_label'):
        t += '; Instagram shows &ldquo;%s&rdquo; in the %s' % (E(p['paid_label']['text']), p['paid_label']['where'])
    return t


